// 190.10.0 Т.к. у нас этот файл подключается к обычной вёрстке, то мы можем повесить классические слушатели события клик на кнопки инкремента и декремента. ↑
// 190.12.0 Рассмотрим ещё одно очень часто встречающееся понятие в Redux — «action creator», а также задачи, которе он решает. Каждый раз, когда мы создаём действие, то прописываем вручную объект и передаём внутрь функции dispatch и это не слишком удобно, особенно если действий станет много и они будут вызывать одни и те же экшены. Поэтому для удобства мы можем создать отдельную функцию, которая будет возвращать этот объект экшена. И тут мы создали 3 функции для каждого вида экшена, которые просто возвращают объект экшена, для более лаконичного использования их в коде. Эти функции и называются «action creator»... ↓
const inc = () => ({type: 'INC'});
const dec = () => ({type: 'DEC'});

// 190.11.0 Мы можем чуть усложнить наш счётчик, добавив ему ещё одну кнопку, которая, по клику на неё, будет умножать стейт на случайное значение от 1 до 10. ↑
const rnd = (value) => ({type: 'RND', payload: value});

// 190.12.1 ..., которые затем очень удобно подставлять в dispatch, делая код более лаконичным и читабельным (этот приём используется повсеместно и лучше к нему сразу привыкнуть).
// ? 190.12.2 В этом подходе есть ещё один приятный бонус, что теперь, если мы где-то ошибёмся и вставим куда-то неправильный action creator, то консоль нам выдаст ошибку (прежде на передачу неизвестного типа экшена редьюсер бы "молча" вернул прежний стейт). ↑
document.getElementById('inc').addEventListener('click', () => store.dispatch(inc()));
document.getElementById('dec').addEventListener('click', () => store.dispatch(dec()));
// 190.11.2 Поэтому, чтобы сохранить функцию-редьюсер "чистой", мы перенесём логику создания случайного числа прямо в обработчик события и уже результат будем передавать в редьюсер, помещая значение в атрибут метода rnd, где он будет передаваться в стейт с помощью пейлоада (это данные, которые мы можем передавать вместе с экшеном в store/редьюсер; "payload" (можно назвать как угодно, но часто принято называть именно так) — означает "полезная нагрузка", доп. данные, которые нам нужно передать вместе с экшеном для дальнейшей обработки). ↑
document.getElementById('rnd').addEventListener('click', () => {
  const value = Math.floor(Math.random() * 10);
  store.dispatch(rnd(value));
});

