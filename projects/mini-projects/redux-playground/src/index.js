/* 190.2 Далее мы будем создавать конструкции очень похожие на те, что мы использовали в уроке объясняющем хук «useReducer» (см. [\react-course-notes\8-179-useReducer.md]). Итак, мы создадим функцию "reducer", которая похожа на обычный стейт и принимает в себя собственно стейт и "action" (действия выполняемые на стейте). Функция-редьюсер должна оставаться "чистой функцией", т.е.:
 1) зависеть исключительно от стейта и action;
 2) возвращать один и тот же результат при одинаковых аргументах (например, если в неё приходит state 1, а action - "INC", то на выходе всегда должна быть 2);
 3) никаких побочных эффектов (не должно быть каких-то посторонних данных, работы с DOM-деревом, console.log или запросов на сервер). Логика функции-редьюсера должна оставаться простой и понятной и не изменяться;
 4) принципы иммутабельности должны соблюдаться (то же самое, что было с функцией setState при использовании хука «useState» — работаем с копией объекта, а не с самим объектом). */
// 190.4 Теперь, ровно также, как мы делали с хуком «useReducer» мы создаём условия, где мы ищем в объекте "action" свойство "type" и считываем его значение. Затем мы выполняем какие-то действия со стейтом в соответствии с наименованием типа экшена (т.е. значения свойства "type"). ↓
// 190.13.0 Ещё стоит отдельно остановиться на работе с объектами и их подвидами. Помним, что при работе со store нам следует соблюдать правила иммутабельности, в том числе и в редьюсере. Заметим, что в каждом случае возвращается объект, также, как и принимается объект в state. Затем, чтобы соблюсти принцип иммутабельности, нам нужно развернуть стейт (этим клонируя их в новый объект) спред-оператором (ведь в нём может содержаться несколько свойств), затем через запятую мы изменяем нужно свойство. Например, в случае с "INC" мы перезаписываем старое свойство "value" на новое, где значением будет сумма прежнего значения стейта и 1. То же сделаем и со всеми остальными. ↓
const reducer = (state = initialState, action) => {
  switch (action.type) {
    // case 'INC':
    //    return state.value + 1;
    case 'INC':
      return {
        ...state,
        value: state.value + 1
      };
    case 'DEC':
      return {
        ...state,
        value: state.value - 1
      };
    // 190.11.1 Но мы не можем здесь просто написать "state * Math.floor(Math.random() * 10)", т.к. это нарушает правила создания функции-редьюсера и является грубой ошибкой. ↓
    // 190.11.3 Затем обращаемся к свойству "payload" объекта "action", чтобы добраться до данных "полезной загрузки" и умножаем его на текущее значение стейта. Т.о. редьюсер останется "чистой" функцией.
    case 'RND':
      return {
        ...state,
        value: state.value * action.payload
      };
    default:
      return state; // в случае с неизвестным типом экшена просто вернём то же значение стейта
  }
};

// 190.6.1 Здесь же мы создадим специальную переменную глобального хранилища "store", куда и помести вызов спец. функции библиотеки redux, а принимать она будет нашу функцию-редьюсер.
// ? 190.6.2 Кстати, в теории можно создавать больше одного store, но в большинстве случаев обходятся одним. ↓
const store = createStore(reducer);

