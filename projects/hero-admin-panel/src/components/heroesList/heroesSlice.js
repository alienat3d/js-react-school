import {createSlice, createAsyncThunk, createEntityAdapter, createSelector} from '@reduxjs/toolkit';
import {useHttp} from '../../hooks/http.hook';

// 209.1.0 Да, мы конечно уже провели на прошлом уроке рефакторинг и избавились здесь от "reducers" [см. heroesSlice2.js], для практического примера, представим, что мы этого не делали и откатим на состояние до этого. У нас тут есть два редьюсера "heroCreated" & "heroDeleted", чтобы создавать и удалять героя. И вот эти функции внутри них мы можем заменить на объект (т.н. "адаптер"), который возвращает метод Redux Toolkit "createEntityAdapter". Внутри этого "объекта-адаптера" есть какие-то методы, коллбеки, мемоизированные селекторы. Большая часть методов такого объекта-адаптера обычно CRUD-операции. И собственно методы, которые будут возвращаться из этого объекта-адаптера и будут манипулировать данными, заключёнными в определённую структуру. Структура эта выглядит как объект с полем "ids", у которого значением массив с уникальными идентификаторами в виде строк или чисел, а также поле "entities" с объектом разных сущностей, связанных с идентификаторами.
// 209.1.1 Итак, создаём этот объект-адаптер при помощи Redux Toolkit метода "createEntityAdapter" из которого потом будем извлекать методы и селекторы. Он создаётся в самом верху слайса, т.к. из него мы будем потом формировать начальное значение слайса.
const heroesAdapter = createEntityAdapter();

// ? 209.2 И да, кстати, при создании адаптера мы могли бы передать в него объект с коллбэк-функциями (в документации (см. ссылки к уроку) есть такой пример). В объект настроек метода "createEntityAdapter" мы передали объект с методами, которые имеют функционал (на самом деле эти две функции уже встроены в стандартный функционал и работают стандартно). Окей, это был всего лишь пример и в нашем мини-проекте это всё пока не нужно. ↓
